/**
 * A Pipeline Lesson's Steps. Each Pipeline Lesson has its own bespoke visual; they share only this shape,
 * so every one of them plugs into the same Player.
 */
export interface PipelineStep {
  /** Unique; doubles as the Marker narration.md anchors to. */
  id: string;
  /** Which part of the pipeline this Step is about; the visual decides what that looks like. */
  stage: string;
  title: string;
}

export interface PipelineData<S extends PipelineStep = PipelineStep> {
  visual: string;
  steps: S[];
  markers: Record<string, number>;
  /** The Lesson's example Program, if it has one. */
  program?: { path: string; lines: string[] };
  /** `javap -c -p` output for the Program, generated by the recorder. */
  bytecode?: string;
}

export function markersFor(steps: PipelineStep[]): Record<string, number> {
  const markers: Record<string, number> = {};
  steps.forEach((s, i) => {
    if (s.id in markers) throw new Error(`Pipeline Step id "${s.id}" appears twice`);
    markers[s.id] = i;
  });
  return markers;
}
